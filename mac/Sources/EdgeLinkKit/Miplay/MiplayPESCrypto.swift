import Foundation

public enum MiplayPESCrypto {
    public static let videoKey = Data([
        0x30, 0x59, 0x30, 0x13, 0x06, 0x07, 0x2A, 0x86,
        0x48, 0xCE, 0x3D, 0x02, 0x01, 0x06, 0x08, 0x2A
    ])

    public static let keyAnnouncementPrefix = Data([
        0x86, 0x48, 0xCE, 0x3D, 0x03, 0x01, 0x07, 0x03, 0x42, 0x00, 0x04
    ])

    public static func isKeyAnnouncementPayload(_ payload: Data) -> Bool {
        payload.starts(with: keyAnnouncementPrefix)
    }

    public static func extractPrivateDataIV(fromPES pes: Data) -> Data? {
        guard pes.count >= 9,
              pes[0] == 0x00, pes[1] == 0x00, pes[2] == 0x01
        else { return nil }
        let flags2 = pes[7]
        let headerLength = Int(pes[8])
        guard pes.count >= 9 + headerLength else { return nil }
        let ptsDTSFlags = (flags2 >> 6) & 0x03
        var offset = 9
        if ptsDTSFlags == 0x02 || ptsDTSFlags == 0x03 {
            offset += 5
            if ptsDTSFlags == 0x03 { offset += 5 }
        }
        guard flags2 & 0x01 != 0, offset < 9 + headerLength else { return nil }
        let extensionByte = pes[offset]
        guard extensionByte & 0x80 != 0 else { return nil }
        let ivStart = offset + 1
        guard ivStart + 16 <= 9 + headerLength, ivStart + 16 <= pes.count else { return nil }
        return Data(pes[ivStart..<(ivStart + 16)])
    }

    public static func decrypt(_ ciphertext: Data, iv: Data, key: Data = videoKey) -> Data {
        crypt(ciphertext, iv: iv, key: key, encrypt: false)
    }

    public static func encrypt(_ plaintext: Data, iv: Data, key: Data = videoKey) -> Data {
        crypt(plaintext, iv: iv, key: key, encrypt: true)
    }

    private static func crypt(_ input: Data, iv: Data, key: Data, encrypt: Bool) -> Data {
        precondition(iv.count == 16)
        guard let aes = AES128(key: key), input.count >= 16 else { return input }
        let blockCount = input.count / 16
        var output = Data(count: input.count)
        var chain = [UInt8](iv)
        input.withUnsafeBytes { inBuf in
            output.withUnsafeMutableBytes { outBuf in
                guard let inBase = inBuf.baseAddress?.assumingMemoryBound(to: UInt8.self),
                      let outBase = outBuf.baseAddress?.assumingMemoryBound(to: UInt8.self)
                else { return }
                for block in 0..<blockCount {
                    let offset = block * 16
                    var value = [UInt8](repeating: 0, count: 16)
                    for i in 0..<16 {
                        value[i] = inBase[offset + i] ^ (encrypt ? chain[i] : 0)
                    }
                    let transformed = encrypt ? aes.encryptBlock(value) : aes.decryptBlock(value)
                    for i in 0..<16 {
                        outBase[offset + i] = transformed[i] ^ (encrypt ? 0 : chain[i])
                        chain[i] = encrypt ? transformed[i] : inBase[offset + i]
                    }
                }
                for i in (blockCount * 16)..<input.count {
                    outBase[i] = inBase[i]
                }
            }
        }
        return output
    }
}

public struct AES128 {
    private let roundKeys: [[UInt8]]

    public init?(key: Data) {
        guard key.count == 16 else { return nil }
        var w = [[UInt8]](repeating: [UInt8](repeating: 0, count: 4), count: 44)
        for i in 0..<4 {
            w[i] = [key[i * 4], key[i * 4 + 1], key[i * 4 + 2], key[i * 4 + 3]]
        }
        for i in 4..<44 {
            var temp = w[i - 1]
            if i % 4 == 0 {
                temp = [temp[1], temp[2], temp[3], temp[0]]
                for j in 0..<4 { temp[j] = Self.sBox[Int(temp[j])] }
                temp[0] ^= Self.rcon[i / 4]
            }
            w[i] = [w[i - 4][0] ^ temp[0], w[i - 4][1] ^ temp[1], w[i - 4][2] ^ temp[2], w[i - 4][3] ^ temp[3]]
        }
        roundKeys = w
    }

    public func encryptBlock(_ input: [UInt8]) -> [UInt8] {
        var s = state(from: input)
        addRoundKey(&s, round: 0)
        for round in 1..<10 {
            subBytes(&s, Self.sBox)
            shiftRows(&s, inverse: false)
            mixColumns(&s, inverse: false)
            addRoundKey(&s, round: round)
        }
        subBytes(&s, Self.sBox)
        shiftRows(&s, inverse: false)
        addRoundKey(&s, round: 10)
        return flatten(s)
    }

    public func decryptBlock(_ input: [UInt8]) -> [UInt8] {
        var s = state(from: input)
        addRoundKey(&s, round: 10)
        for round in stride(from: 9, through: 1, by: -1) {
            shiftRows(&s, inverse: true)
            subBytes(&s, Self.invSBox)
            addRoundKey(&s, round: round)
            mixColumns(&s, inverse: true)
        }
        shiftRows(&s, inverse: true)
        subBytes(&s, Self.invSBox)
        addRoundKey(&s, round: 0)
        return flatten(s)
    }

    private typealias State = [[UInt8]]

    private func state(from input: [UInt8]) -> State {
        var s = State(repeating: [UInt8](repeating: 0, count: 4), count: 4)
        for c in 0..<4 {
            for r in 0..<4 {
                s[r][c] = input[c * 4 + r]
            }
        }
        return s
    }

    private func flatten(_ s: State) -> [UInt8] {
        var out = [UInt8](repeating: 0, count: 16)
        for c in 0..<4 {
            for r in 0..<4 {
                out[c * 4 + r] = s[r][c]
            }
        }
        return out
    }

    private func addRoundKey(_ s: inout State, round: Int) {
        for c in 0..<4 {
            for r in 0..<4 {
                s[r][c] ^= roundKeys[round * 4 + c][r]
            }
        }
    }

    private func subBytes(_ s: inout State, _ box: [UInt8]) {
        for r in 0..<4 {
            for c in 0..<4 {
                s[r][c] = box[Int(s[r][c])]
            }
        }
    }

    private func shiftRows(_ s: inout State, inverse: Bool) {
        for r in 1..<4 {
            var row = [s[r][0], s[r][1], s[r][2], s[r][3]]
            for c in 0..<4 {
                let source = inverse ? (c - r + 4) % 4 : (c + r) % 4
                row[c] = s[r][source]
            }
            for c in 0..<4 { s[r][c] = row[c] }
        }
    }

    private func mixColumns(_ s: inout State, inverse: Bool) {
        for c in 0..<4 {
            let a0 = s[0][c], a1 = s[1][c], a2 = s[2][c], a3 = s[3][c]
            if inverse {
                s[0][c] = mul(0x0E, a0) ^ mul(0x0B, a1) ^ mul(0x0D, a2) ^ mul(0x09, a3)
                s[1][c] = mul(0x09, a0) ^ mul(0x0E, a1) ^ mul(0x0B, a2) ^ mul(0x0D, a3)
                s[2][c] = mul(0x0D, a0) ^ mul(0x09, a1) ^ mul(0x0E, a2) ^ mul(0x0B, a3)
                s[3][c] = mul(0x0B, a0) ^ mul(0x0D, a1) ^ mul(0x09, a2) ^ mul(0x0E, a3)
            } else {
                s[0][c] = mul(0x02, a0) ^ mul(0x03, a1) ^ a2 ^ a3
                s[1][c] = a0 ^ mul(0x02, a1) ^ mul(0x03, a2) ^ a3
                s[2][c] = a0 ^ a1 ^ mul(0x02, a2) ^ mul(0x03, a3)
                s[3][c] = mul(0x03, a0) ^ a1 ^ a2 ^ mul(0x02, a3)
            }
        }
    }

    private func mul(_ a: UInt8, _ b: UInt8) -> UInt8 {
        var a = a, b = b, result: UInt8 = 0
        while b > 0 {
            if b & 1 != 0 { result ^= a }
            a = (a << 1) ^ (a & 0x80 != 0 ? 0x1B : 0)
            b >>= 1
        }
        return result
    }

